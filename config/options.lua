--  10. 信息与消息
-- ============================================================================

o.shortmess = vim.tbl_deep_extend("force", vim.opt.shortmess:get(), {
    s = true, -- 缩短搜索结果消息（如 "42 lines" 替代长文本）
    I = true, -- 禁用启动欢迎界面消息
    c = true, -- 补全信息缩短
    C = true, -- 不显示补全消息
    W = true, -- 缩短写入相关消息
    q = true, -- 缩短退出相关消息
    a = true, -- 使用很多缩写消息
    t = true, -- 缩短 "继续" 提示（用于消息截断时）
})

-- 命令行高度
o.cmdheight = 0 -- 命令行区域高度（默认 1，设为 0 可隐藏但影响 ruler 等）


-- 允许缓冲区在未保存时隐藏（不报错，可切换缓冲区）
-- 不影响保存检查，仍可通过 :w 保存
o.hidden = true

-- 通配符菜单（:edit 或 :find 时按 <Tab> 的补全行为）
o.wildmode = "longest:full,full" -- <Tab> 行为：先补全到最长公共前缀，再显示菜单
o.wildignore = {

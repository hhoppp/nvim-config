o.showcmd = true -- 在命令行右下角显示正在输入的按键

-- 行尾可移动（Normal 模式下 <Left>/<Right> 可跨行）
o.whichwrap:append("<>[]hl")

-- 预览窗口（LSP 自动补全等）不自动跳入
o.winblend = 0


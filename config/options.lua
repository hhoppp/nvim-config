-- 透明背景：在所有插件加载前设置，消除启动闪烁
vim.api.nvim_set_hl(0, "Normal", { bg = "NONE" })

-- ============================================================================
--  1. 缩写与别名
-- ============================================================================

local o = vim.opt   -- 选项缩写
local g = vim.g     -- 全局变量缩写

-- 必须在 keymaps 加载前设置
vim.g.mapleader = " "
vim.g.maplocalleader = " "
local api = vim.api -- API 缩写
local fn = vim.fn   -- 函数缩写

-- ============================================================================
--  2. 编辑器行为
-- ============================================================================

-- 2.1 鼠标
o.mouse = "a" -- 所有模式下启用鼠标（支持分屏拖拽、切换标签等）

-- 2.2 命令超时
o.timeout = false  -- 是否会发生超时
o.timeoutlen = 500 -- 映射序列等待超时（毫秒），默认 1000，调低让快捷键响应更跟手
o.ttimeoutlen = 0  -- 按键码序列超时设为 0，消除 Esc 延迟（搭配 insert mode 使用）

-- 2.3 更新频率
o.updatetime = 300 -- 触发插件回调的间隔（毫秒），影响 gitsigns、lsp 诊断刷新等

-- 2.4 自动读取
o.autoread = true -- 文件在外部被修改后，缓冲区自动读取更新（Vim 无提示切回时生效）

-- ============================================================================
--  3. 显示与界面 (UI)
-- ============================================================================

-- 3.1 行号
o.number = true         -- 显示绝对行号
o.relativenumber = true -- 相对行号（对跳转非常有用，可按需开启）

-- 3.2 高亮当前行
o.cursorline = true -- 高亮光标所在行（方便定位）
-- o.cursorcolumn = false  -- 高亮光标所在列（一般不需要，视觉干扰大）

-- 3.3 符号列（行号左侧区域）
o.signcolumn = "yes" -- 始终显示符号列（诊断图标、git 标记等），防止界面抖动
-- "yes"  = 总是显示
-- "auto" = 有内容时才显示（可能导致窗口左右晃动）
-- "no"   = 不显示

-- 3.4 真彩色
o.termguicolors = true -- 启用 24 位真彩色（终端必须支持，如 Kitty、Alacritty、iTerm2）
-- 检查方法：:echo $TERM 或 :checkhealth

-- 3.5 窗口/状态栏
o.laststatus = 3 -- 全局状态栏（=3 只有一个状态栏，配合 lualine 使用）
-- = 0 从不显示
-- = 1 至少两个窗口时显示
-- = 2 总是显示
-- = 3 全局（Neovim 0.9+，只有一个状态栏）

o.showmode = false -- 不显示 -- INSERT -- 等模式文字（由 lualine 状态栏替代）

-- 3.6 窗口拆分方向
o.splitright = true -- :vsplit 时新窗口在右侧（默认在左侧）
o.splitbelow = true -- :split  时新窗口在下方（默认在上方）

-- 3.7 滚动留边（光标接近边缘时自动滚动，保持上下文）
o.scrolloff = 8     -- 垂直滚动时，光标上下方至少保留 8 行
o.sidescrolloff = 8 -- 水平滚动时，光标左右至少保留 8 列

-- 3.8 文件末尾标记
o.fillchars = {
    eob = " ", -- 文件末尾的 '~' 行替换为空格（更清爽）
    -- vert = "│",        -- 窗口分隔线字符（若不使用主题分隔线可取消注释）
}

-- 3.9 隐藏字符（空格、制表符、行尾等）
o.list = true -- 启用隐藏字符显示
o.listchars = {
    tab = "» ", -- 制表符显示为 » (后面跟空格)
    trail = "·", -- 行尾多余空格显示为 ·
    nbsp = "␣", -- 不换行空格显示为 ␣
    -- extends = "›",      -- 行尾右侧继续符号
    -- precedes = "‹",     -- 行首左侧继续符号
}

-- 3.10 自动换行
o.wrap = false -- 不自动换行（代码编辑推荐 false，markdown 等可设为 true）

-- 3.11 折叠
-- o.foldmethod = "indent" -- 按缩进折叠（需手动开启，LSP 也可用 "expr"）
-- o.foldlevel = 99        -- 默认展开所有折叠（=99 全部展开）
-- o.foldenable = true     -- 启动时启用折叠

-- ============================================================================
--  4. 缩进与制表符
-- ============================================================================

o.tabstop = 4      -- 一个制表符显示的宽度为 4 列
o.shiftwidth = 4   -- >> / << 缩进操作的移动宽度为 4
o.softtabstop = 4  -- 按 <Tab> / <BS> 时插入/删除的空格数（=tabstop 体验一致）
o.expandtab = true -- 将 Tab 转换为空格（推荐，确保跨编辑器格式一致）
-- 如需保留 Tab（如 Makefile）可通过 ftplugin 或 autocmd FileType 覆盖

-- 换行后的代码保持与原行相同的缩进
o.breakindent = true

-- ============================================================================
--  5. 搜索
-- ============================================================================

o.ignorecase = true -- 搜索时忽略大小写（配合 smartcase 使用）
o.smartcase = true  -- 搜索中包含大写字母时自动区分大小写
-- 例如：
--   /hello   → 匹配 hello / Hello / HELLO
--   /Hello   → 只匹配 Hello

o.hlsearch = true  -- 高亮所有匹配结果（用 <C-l> 或 :noh 清除高亮）
o.incsearch = true -- 输入搜索词时即时显示匹配结果（边打边跳转）

-- ============================================================================
--  6. 文件与备份
-- ============================================================================

o.undofile = true -- 持久化撤销历史（关闭文件后仍可 u / Ctrl+r 撤销/重做）
-- 撤销文件保存在 ~/.local/state/nvim/undo/

o.swapfile = false    -- 不创建 .swp 交换文件（undofile 已足够安全，且避免烦人提示）
o.backup = false      -- 不创建备份文件（file.txt~）
o.writebackup = false -- 写入时不创建备份（禁用备份功能）

-- 文件编码
o.encoding = "utf-8"                                -- 内部编码（Vim 内部使用，默认 utf-8）
o.fileencoding = "utf-8"                            -- 文件保存编码
o.fileencodings = "ucs-bom,utf-8,gbk,gb2312,latin1" -- 文件读取编码探测顺序（中文兼容）

-- ============================================================================
--  7. 剪贴板
-- ============================================================================

o.clipboard = "unnamedplus" -- 使用系统剪贴板（"+y / "+p 即系统剪贴板）
-- 效果：y 直接复制到系统剪贴板，p 直接从系统剪贴板粘贴
-- 需系统支持：Linux 需 xclip/xsel, macOS 原生支持, Win 原生支持

-- ============================================================================
--  8. 补全与菜单
-- ============================================================================

o.completeopt = "menu,menuone,noselect"
-- menu       = 显示补全菜单
-- menuone    = 即使只有一个选项也显示菜单
-- noselect   = 不自动选中第一项（方便用 <C-n>/<C-p> 手动选择）
-- 可选附加：preview（显示额外信息，很少用）

o.pumheight = 10 -- 补全菜单最大显示行数（避免补全菜单过长遮挡代码）

